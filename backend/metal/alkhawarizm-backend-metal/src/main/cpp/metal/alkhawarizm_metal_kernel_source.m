         @"                    pv += S[tid][j] * v[k_idx * head_dim + "
         @"head_offset + d];\n"
         @"                }\n"
         @"            }\n"
         @"            O_i[d] = exp_m_diff * O_i[d] + pv;\n"
         @"        }\n"
         @"        \n"
         @"        m_i = m_new;\n"
         @"        l_i = l_new;\n"
         @"    }\n"
         @"    \n"
         @"    // Write out\n"
         @"    if (valid_q) {\n"
         @"        for (uint d = 0; d < head_dim; d++) {\n"
